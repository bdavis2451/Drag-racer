def apply(res):
    for c, g in G.items():
        A = res[c]; dv = g['dv']
        P = lambda pts: [[round(p[0], 2), round(p[1] + dv, 2)] + ([1] if len(p) > 2 else []) for p in pts]
        sh = A['shell']; ua, ub = g['roof']
        idx = [i for i, p in enumerate(sh) if ua < p[0] < ub and p[1] > A['belt'] - 1.5]
        i0, i1 = min(idx), max(idx)
        run = sh[i0:i1 + 1]
        new = P(g['top'])
        if run[0][0] < run[-1][0]: new = new[::-1]
        A['shell'] = sh[:i0] + new + sh[i1 + 1:]
        A['glass'] = [P(x) for x in g['glass']]
        # glass band a touch deeper than read: move its lower edge (and the
        # pillars that follow it) down a little
        top = sorted(g['top'])
        def topAt(u):
            for i in range(len(top) - 1):
                if top[i][0] <= u <= top[i + 1][0]:
                    t = (u - top[i][0]) / (top[i + 1][0] - top[i][0]); return top[i][1] + (top[i + 1][1] - top[i][1]) * t
            return -1e9
        SH = g.get('deep', 0.35)
        A['ws'] = [P([(p[0], p[1] - SH) if p[1] < topAt(p[0]) - 0.3 else p for p in x]) for x in g['ws']]
        A['pillarLit'] = [P([(p[0], p[1] - SH) for p in x]) for x in g['lit'][:2]] 
        A['pillarPaint'] = [P(x) for x in g.get('paintp', [])]
        A['pillars'] = [['trim', P(x)] for x in g['pillars']]
        A['belt'] = round(min(p[1] for p in A['glass'][0]) + dv * 0, 2)
        A.pop('wsGlass', None)
        # interior silhouettes sit low behind the glass
        A['interior'] = [it for it in A.get('interior', []) if it[0] != 'wheel']
