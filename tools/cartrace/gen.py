import numpy as np, cv2, json
def conv(front, rear, ground, ys=0.94):
    L = rear - front
    def f(p): return [round(100 * (rear - p[0]) / L, 2), round(max(0, (ground - p[1]) * 100 / L * ys), 2)]
    return f
def body_poly(name, eps, f):
    b = np.load(name + '_body.npy').astype(np.int32).reshape(-1, 1, 2)
    a = cv2.approxPolyDP(b, eps, True).reshape(-1, 2)
    pts = [f(p) + [1] for p in a]
    return pts
def P(f, pts): return [f(p) for p in pts]
def C(f, pts): return [f(p) + [1] for p in pts]
def J(o): return json.dumps(o, separators=(',', ':'))
